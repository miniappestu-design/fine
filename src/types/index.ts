export type SupportedLocale =
  | 'es'
  | 'pt-PT'
  | 'pt-BR'
  | 'en-US'
  | 'en-GB'
  | 'fr'
  | 'it';

export interface LocaleMeta {
  code: SupportedLocale;
  name: string;
  flag: string;
  nativeName: string;
}

export interface UserProfile {
  id: string;
  displayName: string;
  goals: string[];
  experienceLevel: 'beginner' | 'intermediate' | 'advanced';
  availableTime: number; // in minutes
  preferredDays: string[];
  equipment: string[];
  dietaryPreferences: string[];
  excludedIngredients: string[];
  physicalLimitations?: string;
  reminderPreferences: {
    enabled: boolean;
    time: string; // HH:mm
  };
  preferredLanguage: SupportedLocale;
  onboardingCompleted: boolean;
  createdAt: string;
  updatedAt: string;
}

export type ExerciseCategory =
  | 'mobility'
  | 'full_body'
  | 'upper_body'
  | 'lower_body'
  | 'core_balance'
  | 'low_impact_cardio'
  | 'recovery_stretch';

export interface Exercise {
  id: string;
  category: ExerciseCategory;
  difficulty: 'beginner' | 'intermediate' | 'advanced';
  equipment: string;
  durationSeconds: number;
  repetitions?: string;
  name: Record<SupportedLocale, string>;
  instructions: Record<SupportedLocale, string[]>;
  tips: Record<SupportedLocale, string>;
  alternatives: Record<SupportedLocale, string>;
  precautions: Record<SupportedLocale, string>;
  isCustom?: boolean;
}

export interface Routine {
  id: string;
  title: Record<SupportedLocale, string>;
  description: Record<SupportedLocale, string>;
  level: 'beginner' | 'intermediate' | 'advanced';
  estimatedMinutes: number;
  exerciseIds: string[];
  tags: string[];
  isCustom?: boolean;
}

export type MealType = 'breakfast' | 'lunch' | 'dinner' | 'snack';

export interface RecipeIngredient {
  name: Record<SupportedLocale, string>;
  amount: string;
}

export interface Recipe {
  id: string;
  title: Record<SupportedLocale, string>;
  description: Record<SupportedLocale, string>;
  mealType: MealType;
  prepMinutes: number;
  servings: number;
  ingredients: RecipeIngredient[];
  instructions: Record<SupportedLocale, string[]>;
  allergens: string[];
  tags: string[];
  substitutions?: Record<SupportedLocale, string>;
  isCustom?: boolean;
}

export type HabitCategory =
  | 'movement'
  | 'nutrition'
  | 'recovery'
  | 'mindfulness'
  | 'hydration'
  | 'custom';

export interface Habit {
  id: string;
  title: Record<SupportedLocale, string>;
  description: Record<SupportedLocale, string>;
  category: HabitCategory;
  active: boolean;
  isCustom?: boolean;
  createdAt: string;
}

export interface HabitLog {
  id: string;
  habitId: string;
  date: string; // YYYY-MM-DD
  completed: boolean;
  timestamp: string;
}

export type ActivityType = 'workout' | 'habit' | 'recipe_prepared';

export interface ActivityLog {
  id: string;
  activityType: ActivityType;
  referenceId: string;
  title: string;
  durationMinutes?: number;
  date: string; // YYYY-MM-DD
  timestamp: string;
  notes?: string;
}

export interface MealSlotAssignment {
  dayIndex: number; // 0 = Mon, 6 = Sun
  mealType: MealType;
  recipeId: string;
}

export interface MealPlan {
  id: string;
  userId: string;
  weekStart: string; // YYYY-MM-DD of Monday
  assignments: MealSlotAssignment[];
  updatedAt: string;
}

export interface GroceryItem {
  id: string;
  name: string;
  category: string;
  checked: boolean;
  autoGenerated: boolean;
  sourceRecipeId?: string;
}

export interface ChatMessage {
  id: string;
  role: 'user' | 'assistant' | 'system';
  content: string;
  timestamp: string;
  routineProposal?: any;
  recipeProposal?: any;
}

export type NavTab = 'home' | 'workouts' | 'nutrition' | 'assistant' | 'progress';
