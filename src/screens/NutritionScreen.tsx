import React, { useState } from 'react';
import {
  Search,
  Utensils,
  Calendar,
  ShoppingCart,
  Heart,
  Clock,
  Users,
  Sparkles,
  Check,
  Plus,
  Trash2,
  X,
  AlertTriangle,
  ChevronRight,
  BookOpen,
} from 'lucide-react';
import { useTranslation } from '../i18n';
import { Recipe, MealPlan, GroceryItem, UserProfile, MealType } from '../types';
import { storage } from '../services/storage';
import { generateRecipeWithGemini } from '../services/gemini';

interface NutritionScreenProps {
  profile: UserProfile;
  initialSelectedRecipe?: Recipe | null;
  onClearInitialRecipe?: () => void;
}

export const NutritionScreen: React.FC<NutritionScreenProps> = ({
  profile,
  initialSelectedRecipe,
  onClearInitialRecipe,
}) => {
  const { t, tObj, locale } = useTranslation();

  const [activeTab, setActiveTab] = useState<'recipes' | 'weeklyPlan' | 'groceries'>('recipes');
  const [recipes, setRecipes] = useState<Recipe[]>(() => storage.getRecipes());
  const [favorites, setFavorites] = useState<string[]>(() => storage.getFavorites());
  const [mealPlan, setMealPlan] = useState<MealPlan>(() => storage.getMealPlan());
  const [groceryList, setGroceryList] = useState<GroceryItem[]>(() => storage.getGroceryList());

  // Search & Filter
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedMealType, setSelectedMealType] = useState<string>('all');

  // Recipe Detail Modal
  const [viewingRecipe, setViewingRecipe] = useState<Recipe | null>(initialSelectedRecipe || null);

  // Meal Assignment Modal (assigning a slot in the weekly plan)
  const [assigningSlot, setAssigningSlot] = useState<{ dayIndex: number; mealType: MealType } | null>(
    null
  );

  // Grocery Custom Item Input
  const [customGroceryInput, setCustomGroceryInput] = useState('');

  // AI Meal Generator
  const [showAiMealModal, setShowAiMealModal] = useState(false);
  const [pantryIngredients, setPantryIngredients] = useState('');
  const [aiMealType, setAiMealType] = useState('lunch');
  const [isGenerating, setIsGenerating] = useState(false);
  const [aiGeneratedRecipe, setAiGeneratedRecipe] = useState<any | null>(null);
  const [aiError, setAiError] = useState<string | null>(null);

  // Toggle Favorite
  const handleToggleFavorite = (recipeId: string, e: React.MouseEvent) => {
    e.stopPropagation();
    storage.toggleFavorite(recipeId);
    setFavorites([...storage.getFavorites()]);
  };

  // Assign Recipe to Meal Plan
  const handleAssignRecipe = (recipeId: string) => {
    if (!assigningSlot) return;
    storage.assignMeal(assigningSlot.dayIndex, assigningSlot.mealType, recipeId);
    setMealPlan({ ...storage.getMealPlan() });
    setAssigningSlot(null);
  };

  const handleRemoveMealAssignment = (dayIndex: number, mealType: MealType) => {
    storage.assignMeal(dayIndex, mealType, '');
    setMealPlan({ ...storage.getMealPlan() });
  };

  // Generate Grocery List from Meal Plan
  const handleGenerateGroceries = () => {
    const list = storage.generateGroceriesFromMealPlan(locale);
    setGroceryList([...list]);
    setActiveTab('groceries');
  };

  const handleToggleGroceryItem = (id: string) => {
    const updated = groceryList.map((item) =>
      item.id === id ? { ...item, checked: !item.checked } : item
    );
    storage.saveGroceryList(updated);
    setGroceryList(updated);
  };

  const handleAddCustomGrocery = (e: React.FormEvent) => {
    e.preventDefault();
    if (!customGroceryInput.trim()) return;
    const newItem: GroceryItem = {
      id: `custom-groc-${Date.now()}`,
      name: customGroceryInput.trim(),
      category: 'Manual',
      checked: false,
      autoGenerated: false,
    };
    const updated = [newItem, ...groceryList];
    storage.saveGroceryList(updated);
    setGroceryList(updated);
    setCustomGroceryInput('');
  };

  const handleClearCheckedGroceries = () => {
    const remaining = groceryList.filter((i) => !i.checked);
    storage.saveGroceryList(remaining);
    setGroceryList(remaining);
  };

  // AI Meal Request
  const handleGenerateAiMeal = async () => {
    setIsGenerating(true);
    setAiError(null);
    setAiGeneratedRecipe(null);

    const result = await generateRecipeWithGemini({
      availableIngredients: pantryIngredients,
      mealType: aiMealType,
      userProfile: profile,
      language: locale,
    });

    setIsGenerating(false);
    if (result.success && result.recipe) {
      setAiGeneratedRecipe(result.recipe);
    } else {
      setAiError(result.error || 'No se pudo generar la receta');
    }
  };

  const handleSaveAiRecipe = () => {
    if (!aiGeneratedRecipe) return;

    const newRecipe: Recipe = {
      id: `recipe-ai-${Date.now()}`,
      mealType: (aiGeneratedRecipe.mealType as any) || 'lunch',
      prepMinutes: aiGeneratedRecipe.prepMinutes || 20,
      servings: aiGeneratedRecipe.servings || 2,
      allergens: aiGeneratedRecipe.allergens || [],
      tags: ['gemini_ai', 'equilibrado'],
      isCustom: true,
      title: {
        es: aiGeneratedRecipe.title,
        'pt-PT': aiGeneratedRecipe.title,
        'pt-BR': aiGeneratedRecipe.title,
        'en-US': aiGeneratedRecipe.title,
        'en-GB': aiGeneratedRecipe.title,
        fr: aiGeneratedRecipe.title,
        it: aiGeneratedRecipe.title,
      },
      description: {
        es: aiGeneratedRecipe.description,
        'pt-PT': aiGeneratedRecipe.description,
        'pt-BR': aiGeneratedRecipe.description,
        'en-US': aiGeneratedRecipe.description,
        'en-GB': aiGeneratedRecipe.description,
        fr: aiGeneratedRecipe.description,
        it: aiGeneratedRecipe.description,
      },
      ingredients: (aiGeneratedRecipe.ingredients || []).map((ing: any) => ({
        name: {
          es: ing.name,
          'pt-PT': ing.name,
          'pt-BR': ing.name,
          'en-US': ing.name,
          'en-GB': ing.name,
          fr: ing.name,
          it: ing.name,
        },
        amount: ing.amount || 'Al gusto',
      })),
      instructions: {
        es: aiGeneratedRecipe.instructions || [],
        'pt-PT': aiGeneratedRecipe.instructions || [],
        'pt-BR': aiGeneratedRecipe.instructions || [],
        'en-US': aiGeneratedRecipe.instructions || [],
        'en-GB': aiGeneratedRecipe.instructions || [],
        fr: aiGeneratedRecipe.instructions || [],
        it: aiGeneratedRecipe.instructions || [],
      },
      substitutions: {
        es: aiGeneratedRecipe.substitutions || '',
        'pt-PT': aiGeneratedRecipe.substitutions || '',
        'pt-BR': aiGeneratedRecipe.substitutions || '',
        'en-US': aiGeneratedRecipe.substitutions || '',
        'en-GB': aiGeneratedRecipe.substitutions || '',
        fr: aiGeneratedRecipe.substitutions || '',
        it: aiGeneratedRecipe.substitutions || '',
      },
    };

    storage.addCustomRecipe(newRecipe);
    setRecipes(storage.getRecipes());
    setShowAiMealModal(false);
    setAiGeneratedRecipe(null);
    setViewingRecipe(newRecipe);
  };

  // Filter recipes
  const filteredRecipes = recipes.filter((rec) => {
    if (selectedMealType !== 'all' && rec.mealType !== selectedMealType) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      const title = (rec.title[locale] || rec.title['es']).toLowerCase();
      const desc = (rec.description[locale] || rec.description['es']).toLowerCase();
      const hasIng = rec.ingredients.some((i) =>
        (i.name[locale] || i.name['es']).toLowerCase().includes(q)
      );
      return title.includes(q) || desc.includes(q) || hasIng;
    }
    return true;
  });

  const daysOfWeek: string[] = tObj('nutrition.daysOfWeek') || [
    'Lunes',
    'Martes',
    'Miércoles',
    'Jueves',
    'Viernes',
    'Sábado',
    'Domingo',
  ];

  const mealTypeKeys: MealType[] = ['breakfast', 'lunch', 'dinner', 'snack'];

  return (
    <div className="space-y-6 pb-24 animate-in fade-in duration-200">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
        <div>
          <h1 className="text-2xl font-extrabold text-stone-900 tracking-tight">
            {t('nutrition.title')}
          </h1>
          <p className="text-xs sm:text-sm text-stone-500 mt-0.5">
            {t('nutrition.subtitle')}
          </p>
        </div>

        {/* Gemini Food Assistant Trigger */}
        <button
          onClick={() => setShowAiMealModal(true)}
          className="inline-flex items-center justify-center gap-2 px-4 py-2.5 rounded-2xl bg-gradient-to-r from-amber-700 to-amber-900 text-white text-xs font-semibold shadow-xs hover:shadow-md transition active:scale-95 cursor-pointer self-start sm:self-auto"
        >
          <Sparkles className="w-4 h-4 text-amber-200" />
          <span>{t('nutrition.aiMealBtn')}</span>
        </button>
      </div>

      {/* Navigation Sub-Tabs */}
      <div className="flex items-center gap-1.5 p-1 rounded-2xl bg-stone-100 border border-stone-200 w-full sm:w-max">
        <button
          onClick={() => setActiveTab('recipes')}
          className={`flex-1 sm:flex-initial flex items-center justify-center gap-1.5 px-4 py-2 rounded-xl text-xs font-semibold transition cursor-pointer ${
            activeTab === 'recipes'
              ? 'bg-white text-stone-900 shadow-2xs'
              : 'text-stone-500 hover:text-stone-800'
          }`}
        >
          <BookOpen className="w-3.5 h-3.5" />
          <span>{t('nutrition.tabs.recipes')}</span>
        </button>

        <button
          onClick={() => setActiveTab('weeklyPlan')}
          className={`flex-1 sm:flex-initial flex items-center justify-center gap-1.5 px-4 py-2 rounded-xl text-xs font-semibold transition cursor-pointer ${
            activeTab === 'weeklyPlan'
              ? 'bg-white text-stone-900 shadow-2xs'
              : 'text-stone-500 hover:text-stone-800'
          }`}
        >
          <Calendar className="w-3.5 h-3.5" />
          <span>{t('nutrition.tabs.weeklyPlan')}</span>
        </button>

        <button
          onClick={() => setActiveTab('groceries')}
          className={`flex-1 sm:flex-initial flex items-center justify-center gap-1.5 px-4 py-2 rounded-xl text-xs font-semibold transition cursor-pointer relative ${
            activeTab === 'groceries'
              ? 'bg-white text-stone-900 shadow-2xs'
              : 'text-stone-500 hover:text-stone-800'
          }`}
        >
          <ShoppingCart className="w-3.5 h-3.5" />
          <span>{t('nutrition.tabs.groceries')}</span>
          {groceryList.length > 0 && (
            <span className="w-4 h-4 rounded-full bg-emerald-600 text-white text-[10px] font-bold flex items-center justify-center ml-0.5">
              {groceryList.filter((i) => !i.checked).length}
            </span>
          )}
        </button>
      </div>

      {/* TAB 1: RECIPES CATALOG */}
      {activeTab === 'recipes' && (
        <div className="space-y-4">
          {/* Search Bar & Filters */}
          <div className="flex flex-col sm:flex-row gap-2.5">
            <div className="relative flex-1">
              <Search className="w-4 h-4 absolute left-3.5 top-1/2 -translate-y-1/2 text-stone-400" />
              <input
                type="text"
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                placeholder={t('nutrition.searchPlaceholder')}
                className="w-full pl-10 pr-4 py-2.5 rounded-2xl border border-stone-200 bg-white focus:border-emerald-600 focus:ring-1 focus:ring-emerald-200 text-xs text-stone-900 outline-none transition"
              />
              {searchQuery && (
                <button
                  onClick={() => setSearchQuery('')}
                  className="absolute right-3 top-1/2 -translate-y-1/2 text-stone-400 hover:text-stone-600"
                >
                  <X className="w-4 h-4" />
                </button>
              )}
            </div>

            {/* Meal Type Filter Chips */}
            <div className="flex items-center gap-1.5 overflow-x-auto pb-1">
              {[
                { id: 'all', label: t('nutrition.mealTypes.all') },
                { id: 'breakfast', label: t('nutrition.mealTypes.breakfast') },
                { id: 'lunch', label: t('nutrition.mealTypes.lunch') },
                { id: 'dinner', label: t('nutrition.mealTypes.dinner') },
                { id: 'snack', label: t('nutrition.mealTypes.snack') },
              ].map((m) => (
                <button
                  key={m.id}
                  onClick={() => setSelectedMealType(m.id)}
                  className={`px-3 py-2 rounded-xl text-xs font-medium whitespace-nowrap transition cursor-pointer ${
                    selectedMealType === m.id
                      ? 'bg-amber-800 text-white shadow-2xs font-semibold'
                      : 'bg-white border border-stone-200 text-stone-700 hover:bg-stone-50'
                  }`}
                >
                  {m.label}
                </button>
              ))}
            </div>
          </div>

          {/* Recipes Cards Grid */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {filteredRecipes.map((recipe) => {
              const isFav = favorites.includes(recipe.id);
              const title = recipe.title[locale] || recipe.title['es'];
              const desc = recipe.description[locale] || recipe.description['es'];

              return (
                <div
                  key={recipe.id}
                  onClick={() => setViewingRecipe(recipe)}
                  className="rounded-3xl bg-white p-5 border border-stone-200 shadow-2xs hover:border-amber-300 hover:shadow-xs transition flex flex-col justify-between cursor-pointer group"
                >
                  <div>
                    <div className="flex items-center justify-between text-xs text-stone-500 mb-2">
                      <span className="capitalize px-2.5 py-0.5 rounded-full bg-amber-50 text-amber-900 font-semibold text-[11px]">
                        {recipe.mealType}
                      </span>

                      <button
                        onClick={(e) => handleToggleFavorite(recipe.id, e)}
                        className="p-1.5 rounded-full text-stone-400 hover:text-red-500 transition cursor-pointer"
                        title={isFav ? t('nutrition.favoriteRemoved') : t('nutrition.favoriteAdded')}
                      >
                        <Heart
                          className={`w-4 h-4 ${
                            isFav ? 'fill-red-500 text-red-500' : 'text-stone-400'
                          }`}
                        />
                      </button>
                    </div>

                    <h3 className="text-base font-bold text-stone-900 group-hover:text-amber-950 leading-snug">
                      {title}
                    </h3>
                    <p className="mt-1 text-xs text-stone-600 line-clamp-2 leading-relaxed">
                      {desc}
                    </p>
                  </div>

                  <div className="mt-4 pt-3 border-t border-stone-100 flex items-center justify-between text-xs text-stone-500">
                    <div className="flex items-center gap-3">
                      <span className="flex items-center gap-1">
                        <Clock className="w-3.5 h-3.5 text-stone-400" />
                        {recipe.prepMinutes} min
                      </span>
                      <span className="flex items-center gap-1">
                        <Users className="w-3.5 h-3.5 text-stone-400" />
                        {recipe.servings}
                      </span>
                    </div>

                    <span className="text-xs font-semibold text-amber-800 flex items-center gap-1">
                      {t('home.viewRecipeBtn')}
                      <ChevronRight className="w-3.5 h-3.5" />
                    </span>
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {/* TAB 2: WEEKLY MEAL PLANNER */}
      {activeTab === 'weeklyPlan' && (
        <div className="space-y-4">
          <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3 p-4 rounded-3xl bg-amber-50/70 border border-amber-200">
            <div>
              <h3 className="text-sm font-bold text-amber-950">
                Menú Semanal Equilibrado
              </h3>
              <p className="text-xs text-amber-800 mt-0.5">
                Organiza tus comidas con anticipación para comer mejor sin agobios.
              </p>
            </div>

            <button
              onClick={handleGenerateGroceries}
              className="px-4 py-2.5 rounded-xl bg-amber-800 hover:bg-amber-900 text-white text-xs font-semibold flex items-center justify-center gap-1.5 shadow-2xs transition active:scale-95 cursor-pointer shrink-0"
            >
              <ShoppingCart className="w-4 h-4" />
              <span>{t('nutrition.generateGroceryList')}</span>
            </button>
          </div>

          {/* Days Grid */}
          <div className="space-y-3">
            {Array.from({ length: 7 }).map((_, dayIdx) => {
              const dayName = Array.isArray(daysOfWeek) ? daysOfWeek[dayIdx] : `Día ${dayIdx + 1}`;
              const dayAssignments = mealPlan.assignments.filter((a) => a.dayIndex === dayIdx);

              return (
                <div
                  key={dayIdx}
                  className="rounded-2xl bg-white p-4 border border-stone-200 shadow-2xs"
                >
                  <div className="text-xs font-bold uppercase tracking-wider text-stone-700 mb-2.5">
                    {dayName}
                  </div>

                  <div className="grid grid-cols-2 sm:grid-cols-4 gap-2">
                    {mealTypeKeys.map((mType) => {
                      const assign = dayAssignments.find((a) => a.mealType === mType);
                      const recipe = assign
                        ? recipes.find((r) => r.id === assign.recipeId)
                        : null;

                      return (
                        <div
                          key={mType}
                          className={`p-2.5 rounded-xl border flex flex-col justify-between transition min-h-[72px] ${
                            recipe
                              ? 'bg-amber-50/40 border-amber-200 text-stone-900'
                              : 'bg-stone-50 border-dashed border-stone-300 text-stone-400'
                          }`}
                        >
                          <div className="flex items-center justify-between text-[10px] font-semibold uppercase text-stone-400 mb-1">
                            <span>{mType}</span>
                            {recipe && (
                              <button
                                onClick={() => handleRemoveMealAssignment(dayIdx, mType)}
                                className="text-stone-400 hover:text-red-500 p-0.5"
                                title={t('common.delete')}
                              >
                                <X className="w-3 h-3" />
                              </button>
                            )}
                          </div>

                          {recipe ? (
                            <button
                              onClick={() => setViewingRecipe(recipe)}
                              className="text-left font-bold text-xs text-stone-900 line-clamp-2 hover:underline cursor-pointer"
                            >
                              {recipe.title[locale] || recipe.title['es']}
                            </button>
                          ) : (
                            <button
                              onClick={() => setAssigningSlot({ dayIndex: dayIdx, mealType: mType })}
                              className="w-full flex items-center justify-center gap-1 text-[11px] font-medium text-stone-500 hover:text-emerald-700 py-1 transition cursor-pointer"
                            >
                              <Plus className="w-3.5 h-3.5" />
                              <span>{t('nutrition.emptyPlanSlot')}</span>
                            </button>
                          )}
                        </div>
                      );
                    })}
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {/* TAB 3: GROCERY LIST */}
      {activeTab === 'groceries' && (
        <div className="rounded-3xl bg-white p-5 sm:p-6 border border-stone-200 shadow-2xs space-y-4">
          <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
            <div>
              <h2 className="text-base font-bold text-stone-900">
                {t('nutrition.groceryTitle')}
              </h2>
              <p className="text-xs text-stone-500 mt-0.5">
                {t('nutrition.grocerySubtitle')}
              </p>
            </div>

            {groceryList.some((i) => i.checked) && (
              <button
                onClick={handleClearCheckedGroceries}
                className="text-xs font-semibold text-stone-500 hover:text-red-600 transition cursor-pointer self-start sm:self-auto"
              >
                {t('nutrition.clearChecked')}
              </button>
            )}
          </div>

          {/* Add custom item form */}
          <form onSubmit={handleAddCustomGrocery} className="flex gap-2">
            <input
              type="text"
              value={customGroceryInput}
              onChange={(e) => setCustomGroceryInput(e.target.value)}
              placeholder={t('nutrition.addItemPlaceholder')}
              className="flex-1 px-3.5 py-2.5 rounded-xl border border-stone-200 focus:border-emerald-600 text-xs text-stone-900 outline-none"
            />
            <button
              type="submit"
              className="px-4 py-2.5 rounded-xl bg-emerald-700 hover:bg-emerald-800 text-white text-xs font-semibold transition active:scale-95 cursor-pointer shrink-0"
            >
              {t('nutrition.addItemBtn')}
            </button>
          </form>

          {/* Grocery Items List */}
          {groceryList.length === 0 ? (
            <div className="py-8 text-center text-xs text-stone-400">
              {t('nutrition.noGroceryItems')}
            </div>
          ) : (
            <div className="space-y-2 pt-2">
              {groceryList.map((item) => (
                <div
                  key={item.id}
                  onClick={() => handleToggleGroceryItem(item.id)}
                  className={`flex items-center justify-between p-3 rounded-xl border transition cursor-pointer ${
                    item.checked
                      ? 'bg-stone-50 border-stone-200 text-stone-400 line-through'
                      : 'bg-white border-stone-200 hover:border-emerald-300 text-stone-800'
                  }`}
                >
                  <div className="flex items-center gap-3">
                    <div
                      className={`w-5 h-5 rounded-md border flex items-center justify-center transition ${
                        item.checked
                          ? 'bg-emerald-600 border-emerald-600 text-white'
                          : 'border-stone-300'
                      }`}
                    >
                      {item.checked && <Check className="w-3.5 h-3.5 stroke-[3]" />}
                    </div>
                    <span className="text-xs font-medium">{item.name}</span>
                  </div>

                  <span className="text-[10px] text-stone-400 px-2 py-0.5 rounded-full bg-stone-100">
                    {item.category}
                  </span>
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {/* Recipe Detail Modal */}
      {viewingRecipe && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-xs overflow-y-auto animate-in fade-in">
          <div className="relative w-full max-w-lg rounded-3xl bg-white p-6 shadow-2xl border border-stone-200 text-stone-900 my-8">
            <button
              onClick={() => {
                setViewingRecipe(null);
                if (onClearInitialRecipe) onClearInitialRecipe();
              }}
              className="absolute top-4 right-4 p-1.5 rounded-full text-stone-400 hover:text-stone-700 hover:bg-stone-100 transition"
              aria-label={t('common.close')}
            >
              <X className="w-5 h-5" />
            </button>

            <div className="flex items-center gap-2 text-xs text-amber-800 font-semibold mb-1">
              <span className="capitalize">{viewingRecipe.mealType}</span>
              <span>•</span>
              <span>{viewingRecipe.prepMinutes} min</span>
              <span>•</span>
              <span>{viewingRecipe.servings} {t('nutrition.servings').toLowerCase()}</span>
            </div>

            <h3 className="text-xl font-extrabold text-stone-900">
              {viewingRecipe.title[locale] || viewingRecipe.title['es']}
            </h3>

            <p className="mt-1 text-xs text-stone-600 leading-relaxed">
              {viewingRecipe.description[locale] || viewingRecipe.description['es']}
            </p>

            {/* Ingredients */}
            <div className="mt-4">
              <h4 className="text-xs font-bold uppercase tracking-wider text-stone-500 mb-2">
                {t('nutrition.ingredients')}
              </h4>
              <ul className="space-y-1.5 text-xs text-stone-700">
                {viewingRecipe.ingredients.map((ing, i) => (
                  <li key={i} className="flex items-center justify-between p-2 rounded-lg bg-stone-50">
                    <span>{ing.name[locale] || ing.name['es']}</span>
                    <span className="font-semibold text-stone-500">{ing.amount}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Step-by-Step Instructions */}
            <div className="mt-4">
              <h4 className="text-xs font-bold uppercase tracking-wider text-stone-500 mb-2">
                {t('nutrition.instructions')}
              </h4>
              <ol className="space-y-2 list-decimal list-inside text-xs text-stone-700 leading-relaxed">
                {(viewingRecipe.instructions[locale] || viewingRecipe.instructions['es']).map(
                  (step, idx) => (
                    <li key={idx} className="pl-1">
                      {step}
                    </li>
                  )
                )}
              </ol>
            </div>

            {/* Allergens warning */}
            {viewingRecipe.allergens && viewingRecipe.allergens.length > 0 && (
              <div className="mt-4 p-3 rounded-xl bg-amber-50 border border-amber-200 text-xs text-amber-900 flex items-start gap-2">
                <AlertTriangle className="w-4 h-4 shrink-0 text-amber-700 mt-0.5" />
                <div>
                  <span className="font-semibold">{t('nutrition.allergensWarning')}: </span>
                  {viewingRecipe.allergens.join(', ')}
                </div>
              </div>
            )}

            <button
              onClick={() => {
                setViewingRecipe(null);
                if (onClearInitialRecipe) onClearInitialRecipe();
              }}
              className="mt-6 w-full py-2.5 rounded-xl bg-stone-900 hover:bg-black text-white text-xs font-semibold transition"
            >
              {t('common.close')}
            </button>
          </div>
        </div>
      )}

      {/* Meal Slot Assignment Selector Modal */}
      {assigningSlot && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-xs overflow-y-auto animate-in fade-in">
          <div className="relative w-full max-w-md rounded-3xl bg-white p-6 shadow-2xl border border-stone-200 text-stone-900">
            <button
              onClick={() => setAssigningSlot(null)}
              className="absolute top-4 right-4 p-1.5 rounded-full text-stone-400 hover:text-stone-700 hover:bg-stone-100 transition"
            >
              <X className="w-5 h-5" />
            </button>

            <h3 className="text-base font-bold text-stone-900 mb-1">
              {t('nutrition.selectRecipeToAssign')}
            </h3>
            <p className="text-xs text-stone-500 mb-4 capitalize">
              {daysOfWeek[assigningSlot.dayIndex]} • {assigningSlot.mealType}
            </p>

            <div className="space-y-2 max-h-64 overflow-y-auto pr-1">
              {recipes.map((r) => (
                <button
                  key={r.id}
                  onClick={() => handleAssignRecipe(r.id)}
                  className="w-full flex items-center justify-between p-3 rounded-xl border border-stone-200 hover:bg-amber-50 hover:border-amber-300 text-left transition cursor-pointer"
                >
                  <div>
                    <div className="text-xs font-bold text-stone-900">
                      {r.title[locale] || r.title['es']}
                    </div>
                    <div className="text-[11px] text-stone-500">{r.prepMinutes} min</div>
                  </div>
                  <ChevronRight className="w-4 h-4 text-stone-400" />
                </button>
              ))}
            </div>
          </div>
        </div>
      )}

      {/* AI Food Generator Modal */}
      {showAiMealModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-xs overflow-y-auto animate-in fade-in">
          <div className="relative w-full max-w-lg rounded-3xl bg-white p-6 shadow-2xl border border-stone-200 text-stone-900 my-8">
            <button
              onClick={() => setShowAiMealModal(false)}
              className="absolute top-4 right-4 p-1.5 rounded-full text-stone-400 hover:text-stone-700 hover:bg-stone-100 transition"
            >
              <X className="w-5 h-5" />
            </button>

            <div className="flex items-center gap-2 mb-2">
              <div className="w-8 h-8 rounded-xl bg-amber-100 text-amber-800 flex items-center justify-center">
                <Sparkles className="w-4 h-4" />
              </div>
              <h3 className="text-lg font-bold text-stone-900">
                {t('nutrition.aiMealTitle')}
              </h3>
            </div>
            <p className="text-xs text-stone-500 mb-4">
              {t('nutrition.aiMealDesc')}
            </p>

            <div className="space-y-3">
              <div>
                <label className="block text-xs font-semibold text-stone-700 mb-1">
                  Ingredientes disponibles:
                </label>
                <textarea
                  rows={3}
                  value={pantryIngredients}
                  onChange={(e) => setPantryIngredients(e.target.value)}
                  placeholder={t('nutrition.availableIngredientsPlaceholder')}
                  className="w-full px-3 py-2 rounded-xl border border-stone-200 focus:border-amber-600 text-xs text-stone-900 outline-none"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-stone-700 mb-1">
                  Tipo de comida:
                </label>
                <div className="flex gap-1.5">
                  {['breakfast', 'lunch', 'dinner', 'snack'].map((mt) => (
                    <button
                      key={mt}
                      onClick={() => setAiMealType(mt)}
                      className={`flex-1 py-1.5 rounded-xl text-xs font-medium capitalize border transition cursor-pointer ${
                        aiMealType === mt
                          ? 'border-amber-700 bg-amber-50 text-amber-950 font-semibold'
                          : 'border-stone-200 hover:bg-stone-50 text-stone-700'
                      }`}
                    >
                      {mt}
                    </button>
                  ))}
                </div>
              </div>
            </div>

            {aiError && (
              <div className="mt-4 p-3 rounded-xl bg-red-50 border border-red-200 text-xs text-red-800">
                {aiError}
              </div>
            )}

            {aiGeneratedRecipe && (
              <div className="mt-4 p-4 rounded-2xl bg-amber-50/70 border border-amber-200 space-y-2">
                <div className="flex items-center justify-between">
                  <h4 className="text-sm font-bold text-amber-950">
                    {aiGeneratedRecipe.title}
                  </h4>
                  <span className="text-xs font-semibold text-amber-800">
                    {aiGeneratedRecipe.prepMinutes} min
                  </span>
                </div>
                <p className="text-xs text-stone-700">{aiGeneratedRecipe.description}</p>
              </div>
            )}

            <div className="mt-6">
              {!aiGeneratedRecipe ? (
                <button
                  onClick={handleGenerateAiMeal}
                  disabled={isGenerating}
                  className="w-full py-3 rounded-xl bg-amber-800 hover:bg-amber-900 text-white text-xs font-semibold flex items-center justify-center gap-2 transition active:scale-95 disabled:opacity-50 cursor-pointer"
                >
                  <Sparkles className="w-4 h-4 text-amber-200" />
                  <span>
                    {isGenerating
                      ? t('nutrition.generatingRecipe')
                      : t('nutrition.generateRecipeBtn')}
                  </span>
                </button>
              ) : (
                <button
                  onClick={handleSaveAiRecipe}
                  className="w-full py-3 rounded-xl bg-amber-800 hover:bg-amber-900 text-white text-xs font-semibold shadow-md transition active:scale-95 cursor-pointer"
                >
                  {t('workouts.acceptAndSave')}
                </button>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
